<?php

namespace TusharKhan\DbErrorExplainer\Laravel\Console;

use Illuminate\Console\Command;
use Illuminate\Filesystem\Filesystem;
use Illuminate\Support\Str;
use TusharKhan\DbErrorExplainer\Laravel\DbExplainer;

class FixStubCommand extends Command
{
    use ExplainsPastedErrors;

    protected $description = 'Write the suggested fix for a database error as a migration to review';

    public function __construct(private Filesystem $files)
    {
        $this->signature = 'db:fix-stub ' . self::pastedErrorSignature() . '
            {--path= : Directory for the migration (default database/migrations)}';

        parent::__construct();
    }

    public function handle(DbExplainer $explainer): int
    {
        $diagnosis = $this->diagnose($explainer);
        if ($diagnosis === null) {
            return self::FAILURE;
        }

        $sql = trim($diagnosis->migrationSuggestion['migration_suggestion']);
        if ($sql === '') {
            $this->components->warn("There is no SQL fix for {$diagnosis->errorType}; it is usually fixed in code. Run db:explain for advice.");

            return self::FAILURE;
        }

        $directory = $this->option('path') ?: database_path('migrations');
        $this->files->ensureDirectoryExists($directory);
        $path = $directory . '/' . date('Y_m_d_His') . '_fix_' . Str::snake($diagnosis->errorType) . '.php';
        $this->files->put($path, $this->stub($sql, $diagnosis->explanation));

        $this->components->info("Migration created: {$path}");

        // Suggestions can list alternatives or use placeholder names; running them blindly would be wrong
        if (preg_match('/option \d|^\s*--\s*or\b/im', $sql)) {
            $this->components->warn('The fix lists alternatives. Keep the one you want before migrating.');
        }
        if (preg_match_all('/\byour_\w+/', $sql, $placeholders)) {
            $this->components->warn('Replace the placeholders before migrating: ' . implode(', ', array_unique($placeholders[0])));
        }

        return self::SUCCESS;
    }

    private function stub(string $sql, string $explanation): string
    {
        // One line, and without the PHP close tag, which would end PHP mode inside a // comment
        $about = Str::limit(str_replace(["\r", "\n", '?>'], [' ', ' ', ''], $explanation), 150);

        return <<<PHP
        <?php

        use Illuminate\Database\Migrations\Migration;
        use Illuminate\Support\Facades\DB;

        // Generated by db:fix-stub. Review the SQL before running it.
        // {$about}
        return new class extends Migration
        {
            public function up(): void
            {
                DB::unprepared(<<<'SQL'
        {$this->indent($sql, 12)}
                    SQL);
            }

            public function down(): void
            {
                // Write the reverse of up() if this needs to be rolled back
            }
        };

        PHP;
    }

    private function indent(string $text, int $spaces): string
    {
        return implode("\n", array_map(fn($line) => $line === '' ? '' : str_repeat(' ', $spaces) . $line, explode("\n", $text)));
    }
}
